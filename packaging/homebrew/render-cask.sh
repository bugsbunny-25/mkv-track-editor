#!/usr/bin/env bash
# Prints the Homebrew cask (macOS) for a published release to stdout.
#
#   VERSION=0.2.0 TAP_REPO=bugsbunny-25/homebrew-tap SHA256_MACOS_ARM64=... \
#     packaging/homebrew/render-cask.sh > Casks/mkv-track-editor.rb
#
# A cask, unlike a formula, installs the app into /Applications and keeps it
# there across upgrades. The archive is downloaded from the tap repository's
# GitHub release "mkv-track-editor-v<VERSION>" (the source repository is
# private). DOWNLOAD_BASE overrides the download URL prefix, for local testing.
set -euo pipefail

: "${VERSION:?}" "${TAP_REPO:?}" "${SHA256_MACOS_ARM64:?}"
base=${DOWNLOAD_BASE:-https://github.com/${TAP_REPO}/releases/download/mkv-track-editor-v${VERSION}}

cat <<EOF
# Generated by packaging/homebrew/render-cask.sh in mkv-track-editor's CI.
# Manual edits are overwritten on the next release.
cask "mkv-track-editor" do
  version "${VERSION}"
  sha256 "${SHA256_MACOS_ARM64}"

  url "${base}/mkv-track-editor-#{version}-macos-arm64.tar.gz"
  name "MKV Track Editor"
  desc "Edit MKV tracks with profiles and Radarr/Sonarr-compatible naming"
  homepage "https://github.com/${TAP_REPO}"

  # The app shells out to mkvmerge/mkvpropedit and mediainfo for every
  # analysis and edit.
  depends_on arch: :arm64
  depends_on formula: "media-info"
  depends_on formula: "mkvtoolnix"
  depends_on :macos

  app "mkv-track-editor-#{version}-macos-arm64/MKV Track Editor.app"
  binary "#{appdir}/MKV Track Editor.app/Contents/MacOS/mkv-track-editor"

  zap trash: "~/Library/Application Support/mkv-track-editor"

  caveats <<~CAVEATS
    MKV Track Editor is not notarized by Apple, so macOS blocks its first
    launch after each install or upgrade. Open it once, then choose
    "Open Anyway" in System Settings > Privacy & Security. That also allows
    the mkv-track-editor command, which is the same program.
  CAVEATS
end
EOF
